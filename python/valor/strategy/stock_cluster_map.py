def _build_map() -> dict[str, tuple[str, str]]:
    merged: dict[str, tuple[str, str]] = {}
    for cluster_key, table in (
        ("financial", _FINANCIAL),
        ("real_estate", _REAL_ESTATE),
        ("cyclical_resource", _CYCLICAL_RESOURCE),
        ("manufacturing", _MANUFACTURING),
        ("consumer_staples", _CONSUMER_STAPLES),
        ("consumer_discretionary", _CONSUMER_DISCRETIONARY),
        ("pharma", _PHARMA),
        ("tmt", _TMT),
        ("utility_transport", _UTILITY_TRANSPORT),
        ("conglomerate", _CONGLOMERATE),
    ):
        for code, label in table.items():
            merged[code] = (label, cluster_key)
    return merged


STOCK_CLUSTER_MAP: dict[str, tuple[str, str]] = _build_map()


def lookup_stock_cluster(symbol: str) -> tuple[str, str] | None:
    """Look up a stock's (industry_label, cluster_key) from the static map.

    Returns None if the symbol is not in the map.
    """
    if not symbol:
        return None
    return STOCK_CLUSTER_MAP.get(str(symbol).strip())
